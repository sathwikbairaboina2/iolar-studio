// Copies aiiolar's notebook-sheet components into components/aiiolar-sheet/ so the edition preview draws what aiiolar.com draws.
// Usage: node scripts/sync-aiiolar-sheet.mjs [path-to-aiiolar]   (or set AIIOLAR_DIR)
import { createHash } from 'crypto';
import { execFileSync } from 'child_process';
import { mkdirSync, readFileSync, readdirSync, rmSync, writeFileSync } from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const out = path.join(root, 'components', 'aiiolar-sheet');
const src = path.resolve(process.argv[2] || process.env.AIIOLAR_DIR || 'C:/Users/sathwik/projects/aiiolar');

const SITE = 'site/components/handbook/';
const FILES = [
  'Sheet.tsx', 'Blocks.tsx', 'groups.ts', 'columnFit.ts', 'FitColumns.tsx', 'CodeBlock.tsx', 'Diagram.tsx', 'Flow.tsx',
  'Chain.tsx', 'Flowchart.tsx', 'In.tsx', 'inline.ts', 'motion.ts', 'handbook.module.css',
].map((n) => [n, SITE + n]);
FILES.push(['types.ts', 'src/lib/handbooks/types.ts']);

const HEADER = 'Generated by scripts/sync-aiiolar-sheet.mjs from aiiolar. Do not edit by hand; run npm run sync:aiiolar-sheet.';

/** The studio keeps the handbook contract at lib/publish/contract; the theme switch is html[data-theme] (see ThemeProvider). */
function rewrite(name, text) {
  let t = text
    .replaceAll("'@/lib/handbooks/contract'", "'@/lib/publish/contract'")
    .replaceAll("'@/lib/handbooks/types'", "'./types'");
  if (name === 'types.ts') t = t.replace("from './contract'", "from '@/lib/publish/contract'");
  if (name.endsWith('.css')) t = t.replaceAll("html[data-mode='light']", "html[data-theme='light']");
  const header = name.endsWith('.css') ? `/* ${HEADER} */\n` : `// ${HEADER}\n`;
  return header + t;
}

// Clear stale generated files, but leave anything that is not ours.
mkdirSync(out, { recursive: true });
for (const f of readdirSync(out)) if (/\.(tsx?|css|json)$/.test(f)) rmSync(path.join(out, f));

const files = {};
for (const [name, from] of FILES) {
  const buf = readFileSync(path.join(src, from));
  files[name] = { from, sha256: createHash('sha256').update(buf).digest('hex') };
  writeFileSync(path.join(out, name), rewrite(name, buf.toString('utf8')));
}
const commit = execFileSync('git', ['-C', src, 'rev-parse', 'HEAD'], { encoding: 'utf8' }).trim();
writeFileSync(path.join(out, 'SOURCE.json'), JSON.stringify({ note: HEADER, commit, files }, null, 2) + '\n');
console.log(`copied ${FILES.length} files from ${src} at ${commit.slice(0, 7)}`);
